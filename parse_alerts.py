"""
parse_alerts.py

Reads Suricata alert log lines (fast.log format), pulls out the useful
fields, and stores them in a SQLite database.

This is the Programming (A) component of my project - it takes the real
alert output generated by Suricata (Networking/Cyber Security side) and
turns it into structured, queryable data.

Log line format example:
09/20/2026-05:57:56.000001  [**] [1:1000001:1] CUSTOM Port scan detected -
SYN packet [**] [Classification: (null)] [Priority: 3] {TCP}
192.168.20.100:33775 -> 192.168.10.100:1056
"""

import re
import sqlite3
from pathlib import Path

LOG_FILE = "suricata_alerts.log"
DB_FILE = "alerts.db"

# Regex to pull out: timestamp, SID, message, priority, protocol,
# source IP/port, destination IP/port
ALERT_PATTERN = re.compile(
    r"^(?P<timestamp>\S+)\s+\[\*\*\]\s+"
    r"\[\d+:(?P<sid>\d+):\d+\]\s+"
    r"(?P<message>.*?)\s+\[\*\*\]\s+"
    r"\[Classification:.*?\]\s+"
    r"\[Priority:\s*(?P<priority>\d+)\]\s+"
    r"\{(?P<protocol>\w+)\}\s+"
    r"(?P<src_ip>[\d.]+):(?P<src_port>\d+)\s+->\s+"
    r"(?P<dst_ip>[\d.]+):(?P<dst_port>\d+)"
)


def create_database(conn):
    """Set up the alerts table if it doesn't already exist."""
    conn.execute("""
        CREATE TABLE IF NOT EXISTS alerts (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp TEXT,
            sid TEXT,
            message TEXT,
            priority INTEGER,
            protocol TEXT,
            src_ip TEXT,
            src_port INTEGER,
            dst_ip TEXT,
            dst_port INTEGER
        )
    """)
    conn.commit()


def parse_log_file(log_path):
    """Read the log file and yield a dict for each matched alert line."""
    with open(log_path, "r") as f:
        for line in f:
            match = ALERT_PATTERN.match(line.strip())
            if match:
                data = match.groupdict()
                data["priority"] = int(data["priority"])
                data["src_port"] = int(data["src_port"])
                data["dst_port"] = int(data["dst_port"])
                yield data
            else:
                print(f"Skipped (no match): {line.strip()[:60]}...")


def insert_alert(conn, alert):
    """Insert one parsed alert into the database."""
    conn.execute("""
        INSERT INTO alerts
        (timestamp, sid, message, priority, protocol, src_ip, src_port, dst_ip, dst_port)
        VALUES (:timestamp, :sid, :message, :priority, :protocol, :src_ip, :src_port, :dst_ip, :dst_port)
    """, alert)


def main():
    log_path = Path(LOG_FILE)
    if not log_path.exists():
        print(f"Log file not found: {LOG_FILE}")
        return

    conn = sqlite3.connect(DB_FILE)
    create_database(conn)

    count = 0
    for alert in parse_log_file(log_path):
        insert_alert(conn, alert)
        count += 1

    conn.commit()
    print(f"\nInserted {count} alerts into {DB_FILE}\n")

    # Show what's actually in the database now, as proof it worked
    print("Contents of alerts table:")
    print("-" * 90)
    cursor = conn.execute("""
        SELECT id, timestamp, src_ip, src_port, dst_ip, dst_port, priority, message
        FROM alerts ORDER BY id
    """)
    for row in cursor.fetchall():
        print(row)

    conn.close()


if __name__ == "__main__":
    main()
